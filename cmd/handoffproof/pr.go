// translateDiff rewrites sandbox-root paths (app/...) to repo paths
// (demo-app/...) for a pull request against this repository.
func translateDiff(diff string) string {
	var b strings.Builder
	for _, line := range strings.Split(diff, "\n") {
		line = strings.TrimSuffix(line, "\r") // normalize CRLF diffs for LF clones
		switch {
		case strings.HasPrefix(line, "--- a/app/"):
			line = "--- a/demo-app/" + strings.TrimPrefix(line, "--- a/app/")
		case strings.HasPrefix(line, "+++ b/app/"):
			line = "+++ b/demo-app/" + strings.TrimPrefix(line, "+++ b/app/")
		case strings.HasPrefix(line, "diff --git a/app/"):
			line = strings.Replace(line, "a/app/", "a/demo-app/", 1)
			line = strings.Replace(line, " b/app/", " b/demo-app/", 1)
		}
		b.WriteString(line)
		b.WriteString("\n")
	}
	return controller.EnsureDiffHeaders(strings.TrimRight(b.String(), "\n") + "\n")
}

func diffFiles(diff string) []string {
	seen := map[string]bool{}
	var out []string
	for _, line := range strings.Split(diff, "\n") {
		if strings.HasPrefix(line, "+++ b/") {
			p := strings.TrimSpace(strings.TrimPrefix(line, "+++ b/"))
			if p != "/dev/null" && !seen[p] {
				seen[p] = true
				out = append(out, p)
			}
		}
	}
	return out
}

// cmdPR prepares a guardrailed remediation pull request (F5).
// Default is a dry run: validate, translate, and print the exact plan.
// --execute creates the branch and commit in a throwaway clone only.
// It never pushes and never opens a PR; a human runs the printed gh command.
func cmdPR(ctx context.Context, root string, args []string) error {
	fs := flag.NewFlagSet("pr", flag.ContinueOnError)
	diffPath := fs.String("diff", "", "repair diff file (app/-prefixed paths)")
	title := fs.String("title", "HandoffProof repair: handover credential ownership", "PR title")
	execute := fs.Bool("execute", false, "create branch+commit in a local clone (still no push)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *diffPath == "" {
		return fmt.Errorf("--diff is required")
	}
	raw, err := os.ReadFile(*diffPath)
	if err != nil {
		return err
	}
	diff := string(raw)
	if bad, p := controller.DiffTouchesProtected(diff); bad {
		return fmt.Errorf("guardrail: diff touches protected path %q; PR refused", p)
	}
	repoDiff := translateDiff(diff)
	if bad, p := controller.DiffTouchesProtected(repoDiff); bad {
		return fmt.Errorf("guardrail: translated diff touches protected path %q; PR refused", p)
	}
	branch := fmt.Sprintf("hp/repair-%d", time.Now().Unix())
	files := diffFiles(repoDiff)
	body := fmt.Sprintf("## HandoffProof remediation\n\n%s\n\nFiles: %s\n\nManifest (acceptance integrity): %s\n\nChecklist:\n- [ ] Acceptance suite rerun green in a sandbox copy\n- [ ] Manifest verify passes\n- [ ] No protected path touched (guardrail-enforced)\n\nGenerated by `handoffproof pr`. A human reviews and merges; the agent never merges.",
		*title, strings.Join(files, ", "), manifestHash(root))
	fmt.Println("branch:", branch)
	fmt.Println("files:", strings.Join(files, ", "))
	fmt.Println("title:", *title)
	fmt.Println("--- PR body ---")
	fmt.Println(body)
	fmt.Println("--- commands (human-run) ---")
	fmt.Printf("git checkout -b %s\ngit apply repair.diff\ngit add %s\ngit commit -m %q\ngit push -u origin %s\ngh pr create --title %q --body-file pr-body.md\n",
		branch, strings.Join(files, " "), *title, branch, *title)
	if !*execute {
		fmt.Println("mode: dry-run (no git writes). Re-run with --execute to build the branch in a local clone.")
		return nil
	}
	clone, err := os.MkdirTemp("", "hp-pr-*")
	if err != nil {
		return err
	}
	run := func(name string, args ...string) error {
		cmd := exec.CommandContext(ctx, name, args...)
		cmd.Dir = clone
		out, err := cmd.CombinedOutput()
		if err != nil {
			return fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, out)
		}
		return nil
	}
	// Clone the repo (committed state) into the temp dir itself.
	tmpParent, err := os.MkdirTemp("", "hp-prsrc-*")
	if err != nil {
		return err
	}
	// Kept on success so a human can inspect, push, and open the PR.
	cloneDir := filepath.Join(tmpParent, "repo")
	c := exec.CommandContext(ctx, "git", "-c", "safe.directory="+filepath.ToSlash(root), "-c", "core.autocrlf=false", "clone", "--quiet", root, cloneDir)
	if out, err := c.CombinedOutput(); err != nil {
		return fmt.Errorf("clone: %w: %s", err, out)
	}
	runIn := func(name string, args ...string) error {
		cmd := exec.CommandContext(ctx, name, args...)
		cmd.Dir = cloneDir
		out, err := cmd.CombinedOutput()
		if err != nil {
			return fmt.Errorf("%s: %w: %s", name, err, out)
		}
		return nil
	}
	_ = run
	if err := runIn("git", "checkout", "-b", branch); err != nil {
		return err
	}
	diffFile := filepath.Join(cloneDir, "repair.diff")
	if err := os.WriteFile(diffFile, []byte(repoDiff), 0o644); err != nil {
		return err
	}
	if err := runIn("git", "apply", "--whitespace=nowarn", "--recount", "repair.diff"); err != nil {
		return err
	}
	if err := os.Remove(diffFile); err != nil {
		return err
	}
	if err := runIn("git", "add", "-A"); err != nil {
		return err
	}
	if err := runIn("git", "-c", "user.name=HandoffProof", "-c", "user.email=agent@localhost", "commit", "-m", *title); err != nil {
		return err
	}
	if err := runIn("bash", "scripts/manifest.sh", "verify"); err != nil {
		return fmt.Errorf("manifest verify in clone: %w", err)
	}
	fmt.Println("executed in clone:", cloneDir)
	fmt.Println("branch committed locally. Push and PR creation remain human actions:")
	fmt.Printf("cd %s && git push -u origin %s && gh pr create --title %q\n", cloneDir, branch, *title)
	_ = clone
	return nil
}
